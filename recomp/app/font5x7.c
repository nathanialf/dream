bool font5x7_pixel(char ch, int x, int y) {
  unsigned c = (unsigned char) ch;
  if(c < 0x20 || c > 0x7E) return false;
  if(x < 0 || x >= FONT5X7_W || y < 0 || y >= FONT5X7_H) return false;
  return kGlyphs[c - 0x20][y][x] == '#';
}
